def is_redlined(zip_code: str) -> tuple[bool, str]:
    """
    Returns (is_redlined, reason_string).
    Checks full zip first, then 3-digit prefix.
    """
    z = (zip_code or "").strip()
    if not z:
        return False, ""
    if z in REDLINED_ZIPS:
        city = _ZIP_CITY.get(z, "a historically redlined area")
        return True, f"Zip code {z} is in {city} — a historically redlined geography per HOLC mapping"
    prefix = z[:3]
    if prefix in _HIGH_RISK_PREFIXES:
        return True, (
            f"Zip code {z} is in a high-risk redlining geographic cluster (prefix {prefix}). "
            "This area has documented HOLC grade C/D designations."
        )
    return False, ""


def get_redlined_count() -> int:
    return len(REDLINED_ZIPS)
